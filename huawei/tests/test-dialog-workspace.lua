local profile=assert(arg[1], 'pass the Huawei profile directory')
local env=setmetatable({dofile=function(path) return dofile((path:gsub('^/home/yangfeng/',profile .. '/'))) end},{__index=_G})
local m=assert(loadfile(profile .. '/.config/hypr/scripts/dialog-workspace.lua','t',env))()
local selector=dofile(profile .. '/.config/hypr/scripts/workspace-selector.lua')
local function win(address,pid,id,floating,tags)
 return {address=address,pid=pid,class='pdf',workspace={id=id,name=tostring(id)},floating=floating,tags=tags or {},mapped=true}
end
local dialog=win('new',100,5,true)
local parent=win('parent',100,8,false)
local unrelated=win('other',200,4,false)
assert(m.target(dialog,{dialog,parent,unrelated})==parent.workspace)
print('PASS other processes cannot steal a dialog')
assert(m.target(dialog,{dialog,parent,win('ambiguous',100,9,false)})==nil)
print('PASS ambiguous parent candidates are not guessed from focus')
assert(m.target(win('independent',100,5,false),{parent})==nil)
print('PASS independent same-class window is not rerouted')
assert(m.target(win('forcedfloat',100,5,true),{parent},{pdf=true})==nil)
print('PASS forced-floating application main windows are not dialogs')
assert(m.target(win('modal',100,5,true,{'config-modal'}),{parent},{pdf=true})==parent.workspace)
print('PASS explicit modal tag works for forced-floating applications')
assert(selector({id=-98,name='special:scratchpad'})=='special:scratchpad')
assert(selector({id=-1337,name='notes'})=='name:notes')
assert(selector({id=5,name='5'})=='5')
assert(selector({id=-98})==nil)
print('PASS special/named/numeric workspace selectors')
